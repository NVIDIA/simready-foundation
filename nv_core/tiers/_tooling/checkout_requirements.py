"""Generate a tier checkout's requirement enums for tests that import it.

The enums are codegen output rather than committed source: the wheel build hook
writes them into ``_build/python`` and force-includes them at
``<module>/requirements``. Tests that import a tier from its checkout -- straight
from the source tree, or through an editable install -- need them inside the
checkout instead. An editable install mirrors them there once, at install time,
and any later wheel build removes that mirror again (see
``build_hook.CustomBuildHook._sync_checkout_mirror``).

They are generated *into* the checkout on purpose. A tier is a regular package --
it has an ``__init__.py`` -- so its ``__path__`` is fixed to the checkout
directory and a generated subpackage under another root could not be imported by
adding that root to ``sys.path``. The tier's own ``.gitignore`` already excludes
that directory, because an editable install generates it there too.
"""

from __future__ import annotations

import tomllib
from importlib.util import find_spec
from pathlib import Path


def _build_hook_config(tier_root: Path) -> tuple[str, str]:
    """Read ``module`` and ``reverse_domain`` from the tier's build hook config.

    Taken from ``pyproject.toml`` rather than repeated by callers, so the
    generated package name cannot drift from what the wheel ships.
    """
    pyproject = tomllib.loads((tier_root / "pyproject.toml").read_text(encoding="utf-8"))
    config = pyproject["tool"]["hatch"]["build"]["hooks"]["custom"]
    return config["module"], config["reverse_domain"]


def _resolves_to_installed_wheel(module: str, tier_root: Path) -> bool:
    try:
        spec = find_spec(module)
    except ModuleNotFoundError:
        return False
    if spec is None or spec.origin is None:
        return False
    return tier_root.resolve() not in Path(spec.origin).resolve().parents


def ensure_checkout_requirements(tier_root: Path) -> None:
    """Generate ``<module>.requirements`` into the tier checkout if it is missing.

    Does nothing when the tier imports from an installed wheel, which ships its
    own enums.
    """
    module, reverse_domain = _build_hook_config(tier_root)
    if _resolves_to_installed_wheel(module, tier_root):
        return
    package_root = tier_root / Path(*module.split("."))
    if (package_root / "requirements" / "__init__.py").is_file():
        return

    try:
        from usd_profiles_nvidia.codegen import PythonGenerator
    except ModuleNotFoundError as exc:
        raise RuntimeError(
            f"Cannot generate '{module}.requirements', which the validators import: "
            "usd-profiles-nvidia is not installed. Install the suite's tests/requirements.txt, "
            "or build the tier wheel so the enums are generated by the build hook."
        ) from exc

    # Mirrors the build hook, except that the destination is the checkout
    # rather than _build/python.
    PythonGenerator(
        capabilities_root=str(package_root / "rules_and_reqs"),
        destination_dir=str(tier_root),
        package_name=f"{module}.requirements",
        reverse_domain=reverse_domain,
    ).generate()
